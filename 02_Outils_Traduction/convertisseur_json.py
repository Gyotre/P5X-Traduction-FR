#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
convertisseur_json.py
Compilateur pour Persona 5: The Phantom X.
Lit tous les fichiers JSON de TRADUCTION_FACILE (source unique) et les compile de manière modulaire
(Kits, Consciences, Armes, Cartes, Histoire, UI, Substitutions) directement dans le jeu
et dans TRADUCTION_FR/00_Compiles_Modulaires.

- Chaque clé n'est écrite qu'une seule fois (la première rencontrée gagne, les conflits sont signalés)
- Les substitutions sans traduction sont gardées telles quelles (Nom=Nom), indispensable pour
  que les textes contenant {{A}}, {{B}}... soient reconnus par XUnity
- Configure AutoTranslatorConfig.ini (Language=fr, FromLanguage selon la région)
- Déplace les anciens .txt qui traînent dans le dossier du jeu (sinon ils doublonnent)
- Personnalisation du nom du protagoniste et mode Streameur (masquage d'UID)
"""

import os
import re
import json
import shutil
from datetime import datetime

BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
DIR_EASY = os.path.join(BASE_DIR, 'TRADUCTION_FACILE')
DIR_TRAD_FR = os.path.join(BASE_DIR, 'TRADUCTION_FR')
DIR_COMPILES = os.path.join(DIR_TRAD_FR, '00_Compiles_Modulaires')
BASE_REGEX_FILE = os.path.join(DIR_TRAD_FR, '01_Kits_Personnages', '00_Regex_Dynamiques.txt')
CONFIG_FILE = os.path.join(BASE_DIR, '03_Atelier_Traduction', 'launcher_config.json')

DEFAULT_GAME_DIR = r"E:\SteamLibrary\steamapps\common\P5X\client\pc"

# Correspondance des codes de langue XUnity selon la version du jeu
REGION_LANG_MAP = {
    "EN": "en",
    "JP": "ja",
    "TW": "zh-TW",
    "KR": "ko",
    "CN": "zh-CN"
}

MODULE_NAMES = [
    "00_Regex_Dynamiques.txt",
    "01_Kits_Personnages.txt",
    "02_Histoire_et_Palais.txt",
    "03_Vie_Quotidienne_et_Confidents.txt",
    "04_Evenements_et_Collabs.txt",
    "05_Personas_et_Competences.txt",
    "06_Equipements_Objets_Cartes.txt",
    "07_Interface_et_Combat.txt",
    "_Substitutions.txt",
    "General.txt"
]

# Fichiers gérés par XUnity lui-même : ne jamais les déplacer
XUNITY_FILES = {"_AutoGeneratedTranslations.txt", "_Preprocessors.txt", "_Postprocessors.txt", "_Substitutions.txt"}

DEFAULT_INI = """[Service]
Endpoint=
FallbackEndpoint=

[General]
Language=fr
FromLanguage={from_lang}

[Files]
Directory=Translation/{{Lang}}/Text
OutputFile=Translation/{{Lang}}/Text/_AutoGeneratedTranslations.txt
SubstitutionFile=Translation/{{Lang}}/Text/_Substitutions.txt
PreprocessorsFile=Translation/{{Lang}}/Text/_Preprocessors.txt
PostprocessorsFile=Translation/{{Lang}}/Text/_Postprocessors.txt
"""

def get_config():
    cfg = {
        "game_path": DEFAULT_GAME_DIR,
        "region": "EN",
        "protagoniste_prenom": "",
        "protagoniste_nom": "",
        "masquer_uid": False
    }
    if os.path.exists(CONFIG_FILE):
        try:
            with open(CONFIG_FILE, 'r', encoding='utf-8') as f:
                loaded = json.load(f)
                cfg.update(loaded)
        except Exception:
            pass
    return cfg

def is_regex_key(k):
    return k.startswith('r:') or k.startswith('sr:')

def format_line(k, v):
    """
    Formate proprement une clé/valeur pour XUnity AutoTranslator.
    Gère les regex r:"..."=... et le texte normal Key=Value.
    Échappe les sauts de ligne en \\n pour préserver le format 1 ligne par entrée d'AutoTranslator.
    """
    k = k.strip()
    v = v.strip()
    if not k or not v:
        return None

    def one_line(s):
        return s.replace("\r\n", "\\n").replace("\r", "\\n").replace("\n", "\\n")

    def escape_eq(s):
        # XUnity rejette toute ligne contenant plus d'un = non échappé
        return re.sub(r'(?<!\\)=', r'\\=', s)

    if is_regex_key(k):
        # Valeur toujours entre guillemets (convention P5XTES) : XUnity retire les guillemets
        # extérieurs, ce qui protège ceux de la traduction (<link="s|301">...)
        if v.startswith('"') and v.endswith('"') and len(v) > 1:
            v = v[1:-1]
        return f'{one_line(k)}="{escape_eq(one_line(v))}"\n'

    # Clé normale : échapper les = non déjà échappés
    return f"{escape_eq(one_line(k))}={escape_eq(one_line(v))}\n"

def target_module(k, file, rel_dir):
    """Détermine le fichier compilé de destination d'une entrée."""
    f_low = file.lower()
    if is_regex_key(k) or 'regex' in f_low:
        return "00_Regex_Dynamiques.txt"
    if 'substitut' in f_low or rel_dir.startswith('00_config'):
        return "_Substitutions.txt"
    if rel_dir.startswith('01_personnage'):
        return "01_Kits_Personnages.txt"
    if rel_dir.startswith('02_histoire') or rel_dir.startswith('06_donjon') or 'palais' in f_low:
        return "02_Histoire_et_Palais.txt"
    if rel_dir.startswith('03_vie') or rel_dir.startswith('04_social') or 'confident' in f_low:
        return "03_Vie_Quotidienne_et_Confidents.txt"
    if rel_dir.startswith('05_evenement') or 'collab' in rel_dir or 'persona3' in f_low:
        return "04_Evenements_et_Collabs.txt"
    if rel_dir.startswith('07_persona'):
        return "05_Personas_et_Competences.txt"
    if rel_dir.startswith('08_equipement') or 'carte' in f_low or 'arme' in f_low:
        return "06_Equipements_Objets_Cartes.txt"
    if rel_dir.startswith('09_interface') or rel_dir.startswith('10_combat'):
        return "07_Interface_et_Combat.txt"
    return "General.txt"

def iter_json_files():
    """Parcourt TRADUCTION_FACILE dans un ordre stable (dossiers triés)."""
    for root, dirs, files in os.walk(DIR_EASY):
        dirs.sort()
        rel_dir = os.path.relpath(root, DIR_EASY).replace('\\', '/').lower()
        for file in sorted(files):
            if file.endswith('.json'):
                yield os.path.join(root, file), file, rel_dir

def build_modules(prota_prenom="", prota_nom="", masquer_uid=False, verbose=True):
    """
    Construit le contenu de chaque module compilé.
    Retourne (modules, stats) où stats contient le nombre d'entrées et les conflits.
    """
    modules = {name: [] for name in MODULE_NAMES}
    seen = {}         # clé -> (valeur, fichier source)
    conflicts = []    # (clé, valeur gardée, fichier gardé, valeur ignorée, fichier ignoré)
    duplicates = 0
    errors = []

    # 1. Nom du héros : une substitution Nom=Nom permet à XUnity de reconnaître
    #    les phrases contenant le nom du joueur (remplacé par {{A}} dans les clés)
    for name in [f"{prota_prenom} {prota_nom}".strip(), prota_prenom.strip(), prota_nom.strip()]:
        if name and name not in seen:
            seen[name] = (name, "launcher_config.json")
            modules["_Substitutions.txt"].append(format_line(name, name))

    # 2. Mode Streameur
    if masquer_uid:
        modules["00_Regex_Dynamiques.txt"].append('// --- MODE STREAM (MASQUER UID) ---\n')
        modules["00_Regex_Dynamiques.txt"].append('r:"^ID:(\\d+)$"=""\n\n')

    # 3. Regex de base écrites à la main
    if os.path.exists(BASE_REGEX_FILE):
        with open(BASE_REGEX_FILE, 'r', encoding='utf-8', errors='ignore') as f:
            for line in f:
                s = line.strip()
                if s and not s.startswith('//'):
                    k = re.split(r'(?<!\\)=', s, maxsplit=1)[0]
                    if k not in seen:
                        seen[k] = (s, os.path.basename(BASE_REGEX_FILE))
                        modules["00_Regex_Dynamiques.txt"].append(s + "\n")

    # 4. Tous les JSON de TRADUCTION_FACILE
    for path, file, rel_dir in iter_json_files():
        try:
            with open(path, 'r', encoding='utf-8') as f:
                data = json.load(f)
        except Exception as e:
            errors.append(f"{file}: {e}")
            continue

        rel_file = os.path.relpath(path, DIR_EASY)
        for k, v in data.items():
            key = k.strip()
            val = str(v).strip()
            module = target_module(key, file, rel_dir)

            # Une substitution non traduite garde le nom d'origine
            if not val and module == "_Substitutions.txt":
                val = key
            if not key or not val:
                continue

            if key in seen:
                duplicates += 1
                kept_val, kept_file = seen[key]
                if kept_val != val:
                    conflicts.append((key, kept_val, kept_file, val, rel_file))
                continue

            formatted = format_line(key, val)
            if formatted:
                seen[key] = (val, rel_file)
                modules[module].append(formatted)

    stats = {
        "entries": sum(1 for lines in modules.values() for l in lines if not l.startswith('//') and l.strip()),
        "duplicates": duplicates,
        "conflicts": conflicts,
        "errors": errors
    }

    if verbose:
        for e in errors:
            print(f"[ERREUR] Lecture {e}")
        if conflicts:
            print(f"[ATTENTION] {len(conflicts)} clé(s) traduite(s) différemment dans plusieurs fichiers "
                  f"(la première est gardée) :")
            for key, kv, kf, iv, iff in conflicts[:10]:
                print(f"  - '{key[:60]}'")
                print(f"      gardé   ({kf}) : {kv[:60]}")
                print(f"      ignoré  ({iff}) : {iv[:60]}")
            if len(conflicts) > 10:
                print(f"  ... et {len(conflicts) - 10} autre(s). Lance valider_traductions.py pour la liste complète.")

    return modules, stats

def write_modules(dest_dir, modules):
    """Écrit les modules non vides et supprime ceux devenus vides (générés par nous)."""
    os.makedirs(dest_dir, exist_ok=True)
    written = 0
    for mod_name, lines in modules.items():
        out_p = os.path.join(dest_dir, mod_name)
        if lines:
            with open(out_p, 'w', encoding='utf-8') as f:
                f.writelines(lines)
            written += 1
        elif os.path.exists(out_p) and mod_name not in XUNITY_FILES:
            os.remove(out_p)
    return written

def ensure_xunity_config(game_dir, region="EN"):
    """Crée ou met à jour BepInEx/config/AutoTranslatorConfig.ini pour traduire vers le français."""
    from_lang = REGION_LANG_MAP.get(str(region).upper(), "en")
    cfg_dir = os.path.join(game_dir, 'BepInEx', 'config')
    cfg_file = os.path.join(cfg_dir, 'AutoTranslatorConfig.ini')
    os.makedirs(cfg_dir, exist_ok=True)

    if not os.path.exists(cfg_file):
        with open(cfg_file, 'w', encoding='utf-8') as f:
            f.write(DEFAULT_INI.format(from_lang=from_lang))
        return f"AutoTranslatorConfig.ini créé (de '{from_lang}' vers 'fr')"

    with open(cfg_file, 'r', encoding='utf-8-sig', errors='ignore') as f:
        lines = f.read().splitlines()

    # On ne modifie Language / FromLanguage que dans la section [General]
    out, section, found = [], "", set()
    for line in lines:
        s = line.strip()
        if s.startswith('[') and s.endswith(']'):
            if section == "general":
                if "Language" not in found:
                    out.append("Language=fr")
                if "FromLanguage" not in found:
                    out.append(f"FromLanguage={from_lang}")
                found.update({"Language", "FromLanguage"})
            section = s[1:-1].lower()
        elif section == "general" and s.startswith("Language="):
            line = "Language=fr"
            found.add("Language")
        elif section == "general" and s.startswith("FromLanguage="):
            line = f"FromLanguage={from_lang}"
            found.add("FromLanguage")
        out.append(line)

    if "Language" not in found or "FromLanguage" not in found:
        if section != "general":
            out += ["", "[General]"]
        if "Language" not in found:
            out.append("Language=fr")
        if "FromLanguage" not in found:
            out.append(f"FromLanguage={from_lang}")

    with open(cfg_file, 'w', encoding='utf-8') as f:
        f.write("\n".join(out) + "\n")
    return f"AutoTranslatorConfig.ini vérifié (de '{from_lang}' vers 'fr')"

def move_legacy_files(text_dir):
    """
    Déplace hors du dossier Text les .txt qui ne viennent pas de ce compilateur
    (anciennes copies de TRADUCTION_FR, ancien ManualTranslations.txt...).
    XUnity charge tous les .txt du dossier : sans ça, ils doublonnent nos modules.
    """
    legacy = [f for f in os.listdir(text_dir)
              if f.lower().endswith('.txt') and f not in MODULE_NAMES and f not in XUNITY_FILES]
    if not legacy:
        return 0
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    backup_dir = os.path.join(os.path.dirname(text_dir), f"_anciens_fichiers_{stamp}")
    os.makedirs(backup_dir, exist_ok=True)
    for f in legacy:
        shutil.move(os.path.join(text_dir, f), os.path.join(backup_dir, f))
    print(f"[INFO] {len(legacy)} ancien(s) fichier(s) déplacé(s) dans : {backup_dir}")
    return len(legacy)

def compile_json_to_game(game_dir=None):
    cfg = get_config()
    if not game_dir:
        game_dir = cfg.get("game_path") or DEFAULT_GAME_DIR

    if not os.path.exists(DIR_EASY):
        raise FileNotFoundError(f"Dossier introuvable : {DIR_EASY}")

    print("========================================================")
    print("  COMPILATION MODULAIRE P5X (FORMAT JSON -> JEU)")
    print("========================================================")

    modules, stats = build_modules(
        cfg.get("protagoniste_prenom", "").strip(),
        cfg.get("protagoniste_nom", "").strip(),
        cfg.get("masquer_uid", False)
    )
    total = stats["entries"]
    print(f"Entrées compilées : {total} (doublons ignorés : {stats['duplicates']})")

    # Copie de référence dans TRADUCTION_FR
    write_modules(DIR_COMPILES, modules)

    # Déploiement dans le jeu
    if game_dir and os.path.exists(game_dir):
        dest_game_dir = os.path.join(game_dir, 'BepInEx', 'Translation', 'fr', 'Text')
        os.makedirs(dest_game_dir, exist_ok=True)
        move_legacy_files(dest_game_dir)
        deployed_count = write_modules(dest_game_dir, modules)
        print("[INFO] " + ensure_xunity_config(game_dir, cfg.get("region", "EN")))
        print(f"[SUCCES] {deployed_count} modules deployes dans le jeu :")
        print(f"         {dest_game_dir}")
        print("         Si le jeu est ouvert : Alt + R pour recharger.")
    else:
        print(f"[INFO] Dossier jeu non configure : {game_dir}")

    return total

if __name__ == '__main__':
    import sys
    try:
        compile_json_to_game()
    except Exception as e:
        print(f"[ERREUR] {e}")
        sys.exit(1)
