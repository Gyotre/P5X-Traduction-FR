#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
installer_traductions_dans_jeu.py
Copie et fusionne les fichiers de traduction français dans le dossier du jeu P5X
et configure XUnity.AutoTranslator selon la région du client (EN, JP, TW, KR, CN).
"""

import os
import shutil
import sys
import re

# Correspondance des codes de langue XUnity selon la version du jeu
REGION_LANG_MAP = {
    "EN": "en",       # Global / Steam English
    "JP": "ja",       # Version Japonaise
    "TW": "zh-TW",    # Version Taïwan / Chinois Traditionnel
    "KR": "ko",       # Version Coréenne
    "CN": "zh-CN"     # Version Chine / Chinois Simplifié
}

def deploy_translation(game_dir, region="EN"):
    """
    Copie tous les fichiers de traduction vers {game_dir}/BepInEx/Translation/fr/Text/
    et ajuste la configuration.
    """
    region = region.upper()
    base_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))

    # Si c'est la version EN et que le dossier TRADUCTION_FR existe, on l'utilise en priorité
    trad_fr_dir = os.path.join(base_dir, 'TRADUCTION_FR')
    if region == "EN" and os.path.exists(trad_fr_dir):
        base_tr_dir = trad_fr_dir
    else:
        base_tr_dir = os.path.join(base_dir, '01_Traduction_FR', region)

    if not os.path.exists(base_tr_dir):
        print(f"[ERREUR] Le dossier source pour {region} n'existe pas : {base_tr_dir}")
        return False

    dest_dir = os.path.join(game_dir, 'BepInEx', 'Translation', 'fr', 'Text')
    os.makedirs(dest_dir, exist_ok=True)

    copied = 0
    for root, _, files in os.walk(base_tr_dir):
        for f in files:
            if f.endswith('.txt'):
                src_file = os.path.join(root, f)
                dst_file = os.path.join(dest_dir, f)
                shutil.copy2(src_file, dst_file)
                copied += 1

    # Configuration AutoTranslatorConfig.ini
    cfg_dir = os.path.join(game_dir, 'BepInEx', 'config')
    os.makedirs(cfg_dir, exist_ok=True)
    cfg_file = os.path.join(cfg_dir, 'AutoTranslatorConfig.ini')

    from_lang = REGION_LANG_MAP.get(region, "en")

    if os.path.exists(cfg_file):
        try:
            with open(cfg_file, 'r', encoding='utf-8', errors='ignore') as f:
                content = f.read()
            # Remplacement ou mise à jour de Language et FromLanguage
            if 'Language=' in content:
                content = re.sub(r'Language=\w*', 'Language=fr', content)
            else:
                content += "\nLanguage=fr"

            if 'FromLanguage=' in content:
                content = re.sub(r'FromLanguage=[^\r\n]*', f'FromLanguage={from_lang}', content)
            else:
                content += f"\nFromLanguage={from_lang}"

            with open(cfg_file, 'w', encoding='utf-8') as f:
                f.write(content)
        except Exception as e:
            print(f"[ATTENTION] Impossible d'ajuster le fichier ini : {e}")
    else:
        # Création d'un nouveau fichier ini préconfiguré
        ini_content = f"""[Service]
Endpoint=
FallbackEndpoint=

[General]
Language=fr
FromLanguage={from_lang}

[Files]
Directory=Translation/{{Lang}}/Text
OutputFile=Translation/{{Lang}}/Text/_AutoGeneratedTranslations.txt
SubstitutionFile=Translation/{{Lang}}/Text/_Substitutions.txt
PreprocessorsFile=Translation/{{Lang}}/Text/_Preprocessors.txt
PostprocessorsFile=Translation/{{Lang}}/Text/_Postprocessors.txt

[TextFrameworks]
EnableUGUI=True
EnableTextMesh=True
EnableTextMeshPro=True
EnableNGUI=True
EnableIMGUI=False

[Behaviour]
MaxCharactersPerTranslation=1500
IgnoreWhitespaceInDialogue=True
MinDialogueChars=1
ForceSplitTextByNewline=False
ForceReset=False
EnableUIResizing=True
OverrideFont=
FallbackFontTextMeshPro=
ResizeUIWithCommands=True
OutputHookedTexts=False
"""
        with open(cfg_file, 'w', encoding='utf-8') as f:
            f.write(ini_content)

    print(f"[SUCCÈS] {copied} fichiers ({region} -> FR) déployés dans :")
    print(f"         {dest_dir}")
    print(f"         Configuration : De '{from_lang}' vers 'fr'")
    return True

if __name__ == '__main__':
    if len(sys.argv) < 2:
        print("Usage: python installer_traductions_dans_jeu.py <chemin_dossier_jeu> [EN|JP|TW|KR|CN]")
        print("Exemple: python installer_traductions_dans_jeu.py \"C:\\Games\\P5X\\client\\pc\" EN")
        sys.exit(1)

    game_path = sys.argv[1]
    reg = sys.argv[2] if len(sys.argv) > 2 else "EN"
    deploy_translation(game_path, reg)
