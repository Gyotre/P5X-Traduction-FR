#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
generer_tous_les_json.py
Génère une architecture complète de fichiers JSON faciles à traduire
pour l'INTÉGRALITÉ des textes du jeu Persona 5X.
Classé, catégorisé et préservant à 100% tout le travail déjà effectué.
"""

import os
import re
import json
import shutil

BASE_DIR = r'D:\Anti-Gravity\_Traduction-P5X'
DIR_ORIG = os.path.join(BASE_DIR, 'ORIGINAL_ANGLAIS')
DIR_TRAD_FR = os.path.join(BASE_DIR, 'TRADUCTION_FR')
DIR_EASY = os.path.join(BASE_DIR, 'TRADUCTION_FACILE')
GAME_DIR = r'E:\SteamLibrary\steamapps\common\P5X\client\pc'
GAME_TEXT_DIR = os.path.join(GAME_DIR, 'BepInEx', 'Translation', 'fr', 'Text')

def clean_key(raw):
    s = raw.strip()
    if s.startswith('"') and s.endswith('"') and len(s) >= 2:
        s = s[1:-1]
    return s

def run():
    print("=" * 60)
    print("GÉNÉRATION COMPLÈTE DES JSON DU JEU - CATÉGORISÉS & CLASSÉS")
    print("=" * 60)

    # 1. Collecter TOUTES les traductions françaises existantes pour ne rien perdre
    existing_fr = {}

    # A. Depuis l'ancien TRADUCTION_FACILE (notamment Miku)
    if os.path.exists(DIR_EASY):
        for root, _, files in os.walk(DIR_EASY):
            for f in files:
                if f.endswith('.json'):
                    try:
                        with open(os.path.join(root, f), 'r', encoding='utf-8') as jf:
                            d = json.load(jf)
                            for k, v in d.items():
                                if v and str(v).strip():
                                    existing_fr[clean_key(k)] = str(v).strip()
                    except Exception:
                        pass
    print(f"Traductions existantes récupérées depuis TRADUCTION_FACILE: {len(existing_fr)}")

    # B. Depuis TRADUCTION_FR
    if os.path.exists(DIR_TRAD_FR):
        for root, _, files in os.walk(DIR_TRAD_FR):
            for f in files:
                if f.endswith('.txt'):
                    with open(os.path.join(root, f), 'r', encoding='utf-8', errors='replace') as tf:
                        for line in tf:
                            raw = line.strip()
                            if '=' in raw and not raw.startswith('//') and not raw.startswith('#') and not raw.startswith('r:'):
                                parts = re.split(r'(?<!\\)=', raw, maxsplit=1)
                                if len(parts) == 2:
                                    k, v = clean_key(parts[0]), clean_key(parts[1])
                                    if k and v and k != v and k not in existing_fr:
                                        existing_fr[k] = v

    # C. Depuis les auto-traductions propres du jeu
    auto_game = os.path.join(GAME_TEXT_DIR, '_AutoGeneratedTranslations.txt')
    if os.path.exists(auto_game):
        with open(auto_game, 'r', encoding='utf-8', errors='replace') as af:
            for line in af:
                raw = line.strip()
                if '=' in raw and not raw.startswith('//') and not raw.startswith('#') and not raw.startswith('r:'):
                    if '<sprite' not in raw:
                        parts = re.split(r'(?<!\\)=', raw, maxsplit=1)
                        if len(parts) == 2:
                            k, v = clean_key(parts[0]), clean_key(parts[1])
                            if k and v and k != v and k not in existing_fr:
                                existing_fr[k] = v

    print(f"Total base de données traductions françaises disponibles: {len(existing_fr)}")

    # 2. Créer les répertoires cibles catégorisés
    categories = [
        '01_Personnages',
        '02_Personas_et_Competences',
        '03_Equipements_et_Objets',
        '04_Interface_et_Menus',
        '05_Combat_et_Metavers'
    ]
    for cat in categories:
        os.makedirs(os.path.join(DIR_EASY, cat), exist_ok=True)

    # 3. Traiter 01_Personnages (ThievesSkillsInMenu + ThievesSkillsInBattle)
    menu_file = os.path.join(DIR_ORIG, '01_Kits_Personnages', 'ThievesSkillsInMenuV5.4.2.txt')
    battle_file = os.path.join(DIR_ORIG, '01_Kits_Personnages', 'ThievesSkillsInBattleV5.4.2.txt')
    chars_data = {}

    for src in [menu_file, battle_file]:
        if not os.path.exists(src):
            continue
        current_char = "General_Personnages"
        with open(src, 'r', encoding='utf-8', errors='replace') as f:
            for line in f:
                line_s = line.strip()
                if ' - ' in line_s and len(line_s) < 50 and not '=' in line_s:
                    char_clean = re.sub(r'[^\w\-]', '_', line_s).strip('_')
                    current_char = char_clean
                    if current_char not in chars_data:
                        chars_data[current_char] = {}
                    continue

                if '=' in line_s and not line_s.startswith('//') and not line_s.startswith('#') and not line_s.startswith('r:'):
                    parts = re.split(r'(?<!\\)=', line_s, maxsplit=1)
                    if len(parts) == 2:
                        k = clean_key(parts[0])
                        if k:
                            if current_char not in chars_data:
                                chars_data[current_char] = {}
                            if k not in chars_data[current_char]:
                                chars_data[current_char][k] = existing_fr.get(k, "")

    for char_name, entries in chars_data.items():
        if len(entries) > 0:
            target_path = os.path.join(DIR_EASY, '01_Personnages', f"{char_name}.json")
            with open(target_path, 'w', encoding='utf-8') as out:
                json.dump(entries, out, ensure_ascii=False, indent=2)

    print(f"[OK] 01_Personnages: {len(chars_data)} fichiers personnages créés.")

    # 4. Traiter 02_Personas_et_Competences
    personas_map = {
        'Traits_de_Personas.json': os.path.join(DIR_ORIG, '01_Kits_Personnages', 'PersonaTraits.txt'),
        'Competences_Generales_Menu.json': os.path.join(DIR_ORIG, '01_Kits_Personnages', 'SkillsInMenu.txt'),
        'Competences_Generales_Combat.json': os.path.join(DIR_ORIG, '01_Kits_Personnages', 'SkillsInBattle.txt')
    }

    for json_name, src_txt in personas_map.items():
        if os.path.exists(src_txt):
            d = {}
            with open(src_txt, 'r', encoding='utf-8', errors='replace') as f:
                for line in f:
                    raw = line.strip()
                    if '=' in raw and not raw.startswith('//') and not raw.startswith('#') and not raw.startswith('r:'):
                        parts = re.split(r'(?<!\\)=', raw, maxsplit=1)
                        if len(parts) == 2:
                            k = clean_key(parts[0])
                            if k:
                                d[k] = existing_fr.get(k, "")
            target_path = os.path.join(DIR_EASY, '02_Personas_et_Competences', json_name)
            with open(target_path, 'w', encoding='utf-8') as out:
                json.dump(d, out, ensure_ascii=False, indent=2)

    print(f"[OK] 02_Personas_et_Competences: {len(personas_map)} fichiers créés.")

    # 5. Traiter 03_Equipements_et_Objets
    equip_map = {
        'Armes.json': os.path.join(DIR_ORIG, '02_Equipements_et_Objets', 'Weapons.txt'),
        'Cartes_Revelation.json': os.path.join(DIR_ORIG, '02_Equipements_et_Objets', 'RevelationCards.txt'),
        'Artisanat_Cuisine_et_Boutique.json': os.path.join(DIR_ORIG, '02_Equipements_et_Objets', 'CraftingCookingShopItems.txt')
    }

    for json_name, src_txt in equip_map.items():
        if os.path.exists(src_txt):
            d = {}
            with open(src_txt, 'r', encoding='utf-8', errors='replace') as f:
                for line in f:
                    raw = line.strip()
                    if '=' in raw and not raw.startswith('//') and not raw.startswith('#') and not raw.startswith('r:'):
                        parts = re.split(r'(?<!\\)=', raw, maxsplit=1)
                        if len(parts) == 2:
                            k = clean_key(parts[0])
                            if k:
                                d[k] = existing_fr.get(k, "")
            target_path = os.path.join(DIR_EASY, '03_Equipements_et_Objets', json_name)
            with open(target_path, 'w', encoding='utf-8') as out:
                json.dump(d, out, ensure_ascii=False, indent=2)

    print(f"[OK] 03_Equipements_et_Objets: {len(equip_map)} fichiers créés.")

    # 6. Traiter 04_Interface_et_Menus & 05_Combat_et_Metavers depuis ManualTranslations.txt
    man_txt = os.path.join(DIR_ORIG, '03_Interface_et_Combat', 'ManualTranslations.txt')
    
    ui_buckets = {
        'Systeme_et_Options': {},
        'Menus_Principaux_et_Profil': {},
        'Ville_et_Exploration': {},
        'Gacha_et_Contrats': {},
        'Synergies_et_Activites': {},
        'Missions_et_Pass_de_Combat': {},
        'Evenements_et_Collabs': {},
        'Succes_Titres_et_Objets': {},
        'Metavers_Mementos_et_Epreuves': {},
        'Combat_et_Popups': {},
        'Mots_Cles_et_Noms': {},
        'Autres_Textes_Interface': {}
    }

    current_bucket = 'Systeme_et_Options'

    if os.path.exists(man_txt):
        with open(man_txt, 'r', encoding='utf-8', errors='replace') as f:
            for line in f:
                line_s = line.strip()
                
                # Détection des changements de section
                header = line_s.upper()
                if 'SYSTEM / OPTIONS' in header:
                    current_bucket = 'Systeme_et_Options'
                elif any(h in header for h in ['CHARACTER NAMES', 'RANDOM NAMES', 'WORLDBUILDING TERMS', 'NAMES']):
                    current_bucket = 'Mots_Cles_et_Noms'
                elif any(h in header for h in ['CITY UI', 'AREA NAMES', 'MAP UI']):
                    current_bucket = 'Ville_et_Exploration'
                elif any(h in header for h in ['PROFILE MENU', 'CHARACTER SCREEN', 'CLASS/ STATS SCREEN', 'UNLOCK CONDITIONS', 'WONDER SKILL TREE', 'EXP PAGE']):
                    current_bucket = 'Menus_Principaux_et_Profil'
                elif any(h in header for h in ['HANDBOOK CHALLENGES', 'BATTLE PASS', 'TASKS UI', 'TASKS INFO', 'REQUIREMENTS', 'MISSION SCREEN']):
                    current_bucket = 'Missions_et_Pass_de_Combat'
                elif any(h in header for h in ['CONTRACT', 'PULL SCREEN', 'GACHA RULES', 'GACHAPON', 'CRANE']):
                    current_bucket = 'Gacha_et_Contrats'
                elif any(h in header for h in ['SYNERGY', 'CITY ACTIVITIES', 'MUSIC CLUB', 'SOCCER CLUB', 'CHIHAYA', 'SL']):
                    current_bucket = 'Synergies_et_Activites'
                elif any(h in header for h in ['MEMENTOS', 'METAVERSE FARM', 'VELVET TRIALS', 'VELVET ROOM']):
                    current_bucket = 'Metavers_Mementos_et_Epreuves'
                elif any(h in header for h in ['EVENTS TAB', 'COLLAB', 'EVENT MISSIONS']):
                    current_bucket = 'Evenements_et_Collabs'
                elif any(h in header for h in ['RESOURCES & SHOP', 'ACHIEVEMENTS', 'COSMETICS', 'EMOTES', 'KEY ITEMS']):
                    current_bucket = 'Succes_Titres_et_Objets'
                elif 'OTHERS' in header:
                    current_bucket = 'Autres_Textes_Interface'

                if '=' in line_s and not line_s.startswith('//') and not line_s.startswith('#') and not line_s.startswith('r:'):
                    parts = re.split(r'(?<!\\)=', line_s, maxsplit=1)
                    if len(parts) == 2:
                        k = clean_key(parts[0])
                        if k:
                            ui_buckets[current_bucket][k] = existing_fr.get(k, "")

    # Sauvegarder dans 04_Interface_et_Menus
    for b_name in ['Systeme_et_Options', 'Menus_Principaux_et_Profil', 'Ville_et_Exploration', 
                   'Gacha_et_Contrats', 'Synergies_et_Activites', 'Missions_et_Pass_de_Combat', 
                   'Evenements_et_Collabs', 'Succes_Titres_et_Objets', 'Autres_Textes_Interface']:
        entries = ui_buckets[b_name]
        target_path = os.path.join(DIR_EASY, '04_Interface_et_Menus', f"{b_name}.json")
        with open(target_path, 'w', encoding='utf-8') as out:
            json.dump(entries, out, ensure_ascii=False, indent=2)

    print(f"[OK] 04_Interface_et_Menus: 9 fichiers thématiques créés.")

    # Sauvegarder dans 05_Combat_et_Metavers
    for b_name, sub_name in [('Metavers_Mementos_et_Epreuves', 'Metavers_Mementos_et_Epreuves.json'),
                             ('Combat_et_Popups', 'Combat_et_Popups.json'),
                             ('Mots_Cles_et_Noms', 'Mots_Cles_et_Noms.json')]:
        entries = ui_buckets[b_name]
        target_path = os.path.join(DIR_EASY, '05_Combat_et_Metavers', sub_name)
        with open(target_path, 'w', encoding='utf-8') as out:
            json.dump(entries, out, ensure_ascii=False, indent=2)

    # Ajouter également _Substitutions.txt dans Mots_Cles_et_Substitutions.json
    subs_txt = os.path.join(DIR_ORIG, '04_Configuration_XUnity', '_Substitutions.txt')
    if os.path.exists(subs_txt):
        subs_dict = {}
        with open(subs_txt, 'r', encoding='utf-8', errors='replace') as f:
            for line in f:
                raw = line.strip()
                if '=' in raw and not raw.startswith('//') and not raw.startswith('#') and not raw.startswith('r:'):
                    parts = re.split(r'(?<!\\)=', raw, maxsplit=1)
                    if len(parts) == 2:
                        k = clean_key(parts[0])
                        if k:
                            subs_dict[k] = existing_fr.get(k, clean_key(parts[1]))
        target_path = os.path.join(DIR_EASY, '05_Combat_et_Metavers', 'Substitutions_Noms_et_Termes.json')
        with open(target_path, 'w', encoding='utf-8') as out:
            json.dump(subs_dict, out, ensure_ascii=False, indent=2)

    print(f"[OK] 05_Combat_et_Metavers: 4 fichiers créés.")

    # Nettoyer les anciens dossiers non numérotés s'ils existent dans TRADUCTION_FACILE
    for old_folder in ['Personnages', 'Equipements', 'Interface']:
        old_path = os.path.join(DIR_EASY, old_folder)
        if os.path.exists(old_path):
            shutil.rmtree(old_path, ignore_errors=True)

    print("\n[SUCCÈS TOTAL] L'intégralité des textes du jeu a été découpée et classée dans : TRADUCTION_FACILE/")

if __name__ == '__main__':
    run()
